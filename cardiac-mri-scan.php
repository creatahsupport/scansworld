            <h3 class="fw-semibold mt-3">What is a Cardiac MRI Scan?</h3>
            <p>MRI is a non‑invasive imaging technique that uses magnetic fields and radio waves to produce detailed images of the heart's structure and function without exposure to radiation. <a href="cardiac-mri-scan">Cardiac MRI</a> can show soft tissue details, blood flow patterns and even subtle scarring in the heart muscle that might not be evident on other scans such as the sound waves used in an echocardiogram or the X‑ray images produced by a CT scan.</p>
            
