  <script>
    document.addEventListener("DOMContentLoaded", function () {
      var track = document.getElementById("tncGalleryTrack");
      var prevBtn = document.getElementById("tncGalleryPrev");
      var nextBtn = document.getElementById("tncGalleryNext");
      var dotsWrap = document.getElementById("tncGalleryDots");
      if (!track || !prevBtn || !nextBtn || !dotsWrap) return;

      var slides = Array.prototype.slice.call(track.children);
      var index = 0;

      function visibleCount() {
        return window.innerWidth <= 767 ? 1 : 3;
      }

      function maxIndex() {
        return Math.max(0, slides.length - visibleCount());
      }

      function buildDots() {
        dotsWrap.innerHTML = "";
        var total = maxIndex() + 1;
        for (var i = 0; i < total; i++) {
          var dot = document.createElement("button");
          dot.type = "button";
          dot.className = "tnc-gallery-dot" + (i === index ? " active" : "");
          dot.setAttribute("aria-label", "Go to slide " + (i + 1));
          (function (i) {
            dot.addEventListener("click", function () {
              index = i;
              update();
            });
          })(i);
          dotsWrap.appendChild(dot);
        }
      }

      function update() {
        index = Math.min(Math.max(index, 0), maxIndex());
        var slideWidth = slides[0].getBoundingClientRect().width + 18; // includes gap
        track.style.transform = "translateX(-" + (index * slideWidth) + "px)";
        var dots = dotsWrap.children;
        for (var i = 0; i < dots.length; i++) {
          dots[i].classList.toggle("active", i === index);
        }
      }

      prevBtn.addEventListener("click", function () {
        index = index <= 0 ? maxIndex() : index - 1;
        update();
      });

      nextBtn.addEventListener("click", function () {
        index = index >= maxIndex() ? 0 : index + 1;
        update();
      });

      window.addEventListener("resize", function () {
        buildDots();
        update();
      });

      buildDots();
      update();
    });
  </script>

